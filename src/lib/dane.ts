export function isBuiltinProductCategory(
  slug: string
): slug is ProductCategory {
  return productCategories.includes(slug as ProductCategory);
}

export function labelsFromCustom(
  rows: { slug: string; name: string }[] = []
): Record<string, string> {
  return Object.fromEntries(rows.map((row) => [row.slug, row.name]));
}

export function labelForCategory(
  slug: string,
  extra?: Record<string, string>
): string {
  if (isBuiltinProductCategory(slug)) return categoryLabels[slug];
  return extra?.[slug] ?? slug;
}

